export function castName(region: Region, category: RankingCategory, sequence: number): { symbol: string; name: string } {
  const entry = CAST[region][category][sequence - 1];
  if (!entry) {
    throw new Error(`Sem nome fictício para ${region} ${category} ${sequence}`);
  }
  const [symbol, name] = entry;
  return { symbol, name };
}
